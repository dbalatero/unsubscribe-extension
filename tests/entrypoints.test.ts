import { afterEach, expect, it, vi } from 'vitest';
import { pageUrl, capture, entry } from './fixtures';
import { STORAGE_KEY } from '../src/service';

afterEach(() => { vi.unstubAllGlobals(); vi.resetModules(); vi.doUnmock('../src/collector'); vi.doUnmock('../src/ui'); });
it('wires the background worker to Chrome storage and windows, rejecting foreign callers', async () => {
  const addListener = vi.fn();
  let data: unknown = undefined;
  const get = vi.fn(async () => ({ [STORAGE_KEY]: structuredClone(data) }));
  const set = vi.fn(async value => { data = structuredClone(value[STORAGE_KEY]); });
  const create = vi.fn(async () => ({}));
  vi.stubGlobal('chrome', { runtime: { onMessage: { addListener }, getURL: () => 'chrome-extension://test/index.html' }, storage: { local: { get, set } }, windows: { create } });
  await import('../src/background');
  const listener = addListener.mock.calls[0][0];
  const respond = vi.fn();
  expect(listener({ type: 'open' }, { url: 'https://other.test' }, respond)).toBe(false);
  expect(respond).toHaveBeenCalledWith({ ok: false, error: 'This request is not allowed.' });
  const call = (request: unknown, sender = { url: 'chrome-extension://test/index.html', frameId: 0 }) => new Promise(resolve => { expect(listener(request, sender, resolve)).toBe(true); });
  await call({ type: 'capture', capture }, { url: pageUrl, frameId: 0 });
  expect(get).toHaveBeenCalledWith(STORAGE_KEY);
  expect(set).toHaveBeenCalled();
  await call({ type: 'open' });
  expect(create).toHaveBeenCalledWith({ url: [capture.url], type: 'normal', focused: true });
});
it('wires content capture, failed replies, warnings and cleanup', async () => {
  const stop = vi.fn();
  const collect = vi.fn(() => stop);
  vi.doMock('../src/collector', () => ({ collect }));
  const sendMessage = vi.fn().mockResolvedValueOnce({ ok: true, entries: [entry] }).mockResolvedValueOnce({ ok: false, error: 'Cannot save' });
  vi.stubGlobal('chrome', { runtime: { sendMessage } });
  const warn = vi.spyOn(console, 'warn').mockImplementation(() => {});
  await import('../src/content');
  const [doc, getUrl, save, report] = collect.mock.calls[0] as unknown as [Document, () => string, (c: unknown) => Promise<void>, () => void];
  expect(doc).toBe(document);
  expect(getUrl()).toBe(location.href);
  await save(capture);
  expect(sendMessage).toHaveBeenCalledWith({ type: 'capture', capture });
  await expect(save(capture)).rejects.toThrow('Cannot save');
  report();
  expect(warn).toHaveBeenCalled();
  window.dispatchEvent(new Event('pagehide'));
  expect(stop).toHaveBeenCalledOnce();
});
it('wires review startup and local storage refreshes', async () => {
  document.body.innerHTML = '<main id="app"></main>';
  const refresh = vi.fn();
  const mount = vi.fn(() => ({ refresh }));
  vi.doMock('../src/ui', () => ({ mount }));
  const sendMessage = vi.fn();
  const addListener = vi.fn();
  vi.stubGlobal('chrome', { runtime: { sendMessage }, storage: { onChanged: { addListener } } });
  await import('../src/review');
  const [root, send] = mount.mock.calls[0] as unknown as [HTMLElement, (r: unknown) => void];
  expect(root.id).toBe('app');
  send({ type: 'list' });
  expect(sendMessage).toHaveBeenCalledWith({ type: 'list' });
  addListener.mock.calls[0][0]({}, 'sync');
  expect(refresh).not.toHaveBeenCalled();
  addListener.mock.calls[0][0]({}, 'local');
  expect(refresh).toHaveBeenCalledOnce();
});
